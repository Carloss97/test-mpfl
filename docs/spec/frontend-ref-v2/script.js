function updateMenuLabel() {
    if (!menuButton) return;
    const open = menuButton.getAttribute('aria-expanded') === 'true';
    menuButton.setAttribute('aria-label', translations[currentLanguage][open ? 'menuClose' : 'menuOpen']);
}

function setLanguage(language, persist = false) {
    currentLanguage = Object.hasOwn(translations, language) ? language : 'en';
    const copy = translations[currentLanguage];
    document.documentElement.lang = currentLanguage;
    document.querySelectorAll('[data-i18n]').forEach(element => {
        element.textContent = copy[element.dataset.i18n];
    });
    ['alt', 'aria-label', 'content'].forEach(attribute => {
        document.querySelectorAll('[data-i18n-' + attribute + ']').forEach(element => {
            element.setAttribute(attribute, copy[element.getAttribute('data-i18n-' + attribute)]);
        });
    });
    languageButtons.forEach(button => {
        button.setAttribute('aria-pressed', String(button.dataset.language === currentLanguage));
    });
    updateMenuLabel();
    if (persist) {
        try {
            localStorage.setItem(languageStorageKey, currentLanguage);
        } catch {
            // Language switching still works when browser storage is unavailable.
        }
    }
}

languageButtons.forEach(button => {
    button.addEventListener('click', () => setLanguage(button.dataset.language, true));
});

let savedLanguage = 'en';
try {
    savedLanguage = localStorage.getItem(languageStorageKey) || 'en';
} catch {
    // Keep the English default if browser storage is blocked.
}
setLanguage(savedLanguage);

function closeMenu() {
    nav.classList.remove('mobile-open');
    menuButton.setAttribute('aria-expanded', 'false');
    updateMenuLabel();
}

if (menuButton && nav) {
    menuButton.addEventListener('click', () => {
        const open = nav.classList.toggle('mobile-open');
        menuButton.setAttribute('aria-expanded', String(open));
        updateMenuLabel();
    });
    nav.querySelectorAll('a').forEach(link => link.addEventListener('click', closeMenu));
    document.addEventListener('keydown', event => {
        if (event.key === 'Escape' && menuButton.getAttribute('aria-expanded') === 'true') {
            closeMenu();
            menuButton.focus();
        }
    });
    window.matchMedia('(max-width: 1150px)').addEventListener('change', closeMenu);
}
